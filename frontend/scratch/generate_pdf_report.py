import os
import csv
from fpdf import FPDF

# Custom styled PDF class
class VitaWatchPDF(FPDF):
    def header(self):
        # Top banner with custom branding and gradient effect
        self.set_fill_color(11, 21, 40) # Deep Navy background
        self.rect(0, 0, 210, 30, 'F')
        
        self.set_text_color(0, 212, 255) # Neon Blue
        self.set_font('Helvetica', 'B', 16)
        self.cell(0, 10, ' VITAWATCH AI  |  CLINICAL REPORT', ln=True)
        
        self.set_text_color(150, 150, 150)
        self.set_font('Helvetica', 'I', 8)
        self.cell(0, 5, 'Next-Generation Medical OS & Health Analytics Summary', ln=True)
        
        # Color bar divider
        self.set_fill_color(168, 85, 247) # Neon Purple divider
        self.rect(0, 29, 210, 1, 'F')
        self.ln(12)

    def footer(self):
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f'Page {self.page_no()} of {{nb}}  |  System Status: Online  |  Generated by VitaWatch Health Engine', align='C')

def generate_report():
    reports_dir = r"C:\Users\SANDEEP ROSHAN S D\OneDrive\Desktop\VitaWatchAI\vitawatch_dummy_reports"
    output_pdf = os.path.join(reports_dir, "vitawatch_clinical_summary.pdf")
    
    # 1. Parse CSV Data
    vitals_file = os.path.join(reports_dir, "vitals_telemetry.csv")
    sleep_file = os.path.join(reports_dir, "sleep_analytics.csv")
    mood_file = os.path.join(reports_dir, "mood_stress_logs.csv")
    cog_file = os.path.join(reports_dir, "cognitive_performance.csv")
    em_file = os.path.join(reports_dir, "emergency_incidents.csv")

    # Read and process Vitals Telemetry
    avg_hr, avg_hrv, avg_spo2, avg_stress = 0, 0, 0, 0
    vitals_count = 0
    if os.path.exists(vitals_file):
        with open(vitals_file, 'r') as f:
            reader = csv.DictReader(f)
            for row in reader:
                avg_hr += int(row['Heart_Rate_BPM'])
                avg_hrv += int(row['HRV_ms'])
                avg_spo2 += int(row['SpO2_Percent'])
                avg_stress += int(row['Stress_Score'])
                vitals_count += 1
        if vitals_count > 0:
            avg_hr = round(avg_hr / vitals_count, 1)
            avg_hrv = round(avg_hrv / vitals_count, 1)
            avg_spo2 = round(avg_spo2 / vitals_count, 1)
            avg_stress = round(avg_stress / vitals_count, 1)

    # Read Sleep
    sleep_rows = []
    if os.path.exists(sleep_file):
        with open(sleep_file, 'r') as f:
            reader = csv.DictReader(f)
            sleep_rows = list(reader)

    # Read Cognitive Performance
    cog_rows = []
    if os.path.exists(cog_file):
        with open(cog_file, 'r') as f:
            reader = csv.DictReader(f)
            cog_rows = list(reader)

    # Read Incidents
    em_rows = []
    if os.path.exists(em_file):
        with open(em_file, 'r') as f:
            reader = csv.DictReader(f)
            em_rows = list(reader)

    # 2. Build PDF
    pdf = VitaWatchPDF()
    pdf.alias_nb_pages()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    # Title Card block
    pdf.set_fill_color(245, 247, 250)
    pdf.rect(10, 42, 190, 22, 'F')
    pdf.set_xy(12, 44)
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_text_color(11, 21, 40)
    pdf.cell(0, 6, "Patient: Sandeep Roshan", ln=True)
    pdf.set_font('Helvetica', '', 10)
    pdf.set_text_color(100, 100, 100)
    pdf.cell(0, 5, "Age: 24  |  Height: 5'10\"  |  Weight: 72kg  |  Status Rank: Premium Level", ln=True)
    pdf.ln(10)

    # Metric summary block
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_text_color(11, 21, 40)
    pdf.cell(0, 8, "1. Vitals Analytics & Stress Summary", ln=True)
    
    # Draw metrics grid boxes
    box_w = 44
    box_h = 20
    metrics = [
        ("Avg Heart Rate", f"{avg_hr} BPM", (0, 212, 255)),
        ("Avg HRV", f"{avg_hrv} ms", (168, 85, 247)),
        ("Avg SpO2", f"{avg_spo2}%", (0, 255, 136)),
        ("Avg Stress", f"{avg_stress}/100", (255, 51, 102))
    ]
    
    curr_x = 10
    curr_y = pdf.get_y()
    for label, val, color in metrics:
        pdf.set_fill_color(240, 244, 248)
        pdf.rect(curr_x, curr_y, box_w, box_h, 'F')
        
        pdf.set_xy(curr_x + 2, curr_y + 3)
        pdf.set_font('Helvetica', '', 8)
        pdf.set_text_color(100, 100, 100)
        pdf.cell(box_w - 4, 4, label, ln=True)
        
        pdf.set_xy(curr_x + 2, curr_y + 10)
        pdf.set_font('Helvetica', 'B', 12)
        pdf.set_text_color(*color)
        pdf.cell(box_w - 4, 6, val, ln=True)
        curr_x += box_w + 4
        
    pdf.set_xy(10, curr_y + box_h + 8)

    # 2. Sleep Quality Table
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_text_color(11, 21, 40)
    pdf.cell(0, 8, "2. Sleep Performance Log (Last 7 Days)", ln=True)
    
    pdf.set_font('Helvetica', 'B', 9)
    pdf.set_fill_color(11, 21, 40)
    pdf.set_text_color(255, 255, 255)
    
    # Table headers
    headers = ["Date", "Total (h)", "Deep (h)", "REM (h)", "Light (h)", "Awake (m)", "Score"]
    col_w = [25, 25, 25, 25, 25, 30, 35]
    
    for i, h in enumerate(headers):
        pdf.cell(col_w[i], 7, h, 1, 0, 'C', True)
    pdf.ln()

    pdf.set_font('Helvetica', '', 9)
    pdf.set_text_color(50, 50, 50)
    for row in sleep_rows:
        pdf.cell(col_w[0], 6, row['Date'], 1, 0, 'C')
        pdf.cell(col_w[1], 6, row['Total_Sleep_Hours'], 1, 0, 'C')
        pdf.cell(col_w[2], 6, row['Deep_Sleep_Hours'], 1, 0, 'C')
        pdf.cell(col_w[3], 6, row['REM_Sleep_Hours'], 1, 0, 'C')
        pdf.cell(col_w[4], 6, row['Light_Sleep_Hours'], 1, 0, 'C')
        pdf.cell(col_w[5], 6, row['Awake_Minutes'], 1, 0, 'C')
        pdf.cell(col_w[6], 6, row['Sleep_Quality_Score'], 1, 1, 'C')
    pdf.ln(5)

    # 3. Cognitive Performance Table
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_text_color(11, 21, 40)
    pdf.cell(0, 8, "3. AR Cognitive Reflex & Target Performance", ln=True)
    
    pdf.set_font('Helvetica', 'B', 9)
    pdf.set_fill_color(11, 21, 40)
    pdf.set_text_color(255, 255, 255)
    
    headers_cog = ["Test Date", "Reaction (ms)", "Hits", "Accuracy", "Focus", "Reflex Rating"]
    col_w_cog = [30, 30, 25, 30, 30, 45]
    
    for i, h in enumerate(headers_cog):
        pdf.cell(col_w_cog[i], 7, h, 1, 0, 'C', True)
    pdf.ln()

    pdf.set_font('Helvetica', '', 9)
    pdf.set_text_color(50, 50, 50)
    for row in cog_rows[:5]: # Show top 5 entries
        pdf.cell(col_w_cog[0], 6, row['Test_Date'], 1, 0, 'C')
        pdf.cell(col_w_cog[1], 6, row['Reaction_Time_ms'], 1, 0, 'C')
        pdf.cell(col_w_cog[2], 6, row['Target_Hits'], 1, 0, 'C')
        pdf.cell(col_w_cog[3], 6, row['Accuracy_Percent'] + "%", 1, 0, 'C')
        pdf.cell(col_w_cog[4], 6, row['Focus_Score_1_100'], 1, 0, 'C')
        pdf.cell(col_w_cog[5], 6, row['Reflex_Rating'], 1, 1, 'C')
    pdf.ln(5)

    # 4. Emergency Incident log
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_text_color(11, 21, 40)
    pdf.cell(0, 8, "4. Fall & Cardiac Emergency Logs", ln=True)
    
    pdf.set_font('Helvetica', 'B', 9)
    pdf.set_fill_color(255, 51, 102) # Crimson alert background
    pdf.set_text_color(255, 255, 255)
    
    headers_em = ["Timestamp", "Incident Event", "Location", "Severity", "GPS Coordinates"]
    col_w_em = [40, 35, 30, 25, 60]
    
    for i, h in enumerate(headers_em):
        pdf.cell(col_w_em[i], 7, h, 1, 0, 'C', True)
    pdf.ln()

    pdf.set_font('Helvetica', '', 8)
    pdf.set_text_color(50, 50, 50)
    for row in em_rows:
        time_clean = row['Timestamp'].replace('Z', '').split('T')
        time_str = f"{time_clean[0]} {time_clean[1][:5]}"
        pdf.cell(col_w_em[0], 6, time_str, 1, 0, 'C')
        pdf.cell(col_w_em[1], 6, row['Incident_Type'], 1, 0, 'C')
        pdf.cell(col_w_em[2], 6, row['Detected_Location'], 1, 0, 'C')
        pdf.cell(col_w_em[3], 6, row['Fall_Severity'], 1, 0, 'C')
        pdf.cell(col_w_em[4], 6, row['GPS_Coordinates'], 1, 1, 'C')

    pdf.output(output_pdf)
    print(f"PDF Successfully generated at {output_pdf}")

if __name__ == "__main__":
    generate_report()
